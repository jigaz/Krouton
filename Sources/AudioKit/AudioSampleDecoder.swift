/// Result of decoding and mastering one or more audio files into a Red Book Audio CD `.bin` + `.cue` pair.
public struct AudioMasteredDiscResult: Sendable, Equatable {
    public let binURL: URL
    public let cueURL: URL
    public let totalSectors2352: Int
    public let totalBytes: Int64
    public let cueSheetText: String
}

extension KroutonAudioEngine {
    /// Decodes any macOS-supported audio file (.wav, .aiff, .m4a, .mp3, .flac) into raw
    /// 44.1 kHz, 16-bit, 2-channel signed little-endian Red Book Audio CD PCM bytes, padded to a 2,352-byte sector multiple.
    @available(macOS, deprecated: 15.0)
        private static func loadFirstAudioTrackSync(from asset: AVURLAsset) -> AVAssetTrack? {
        final class Box: @unchecked Sendable { var track: AVAssetTrack? }
        let box = Box()
        let sem = DispatchSemaphore(value: 0)
        Task.detached {
            box.track = try? await asset.loadTracks(withMediaType: .audio).first
            sem.signal()
        }
        sem.wait()
        return box.track
    }

    public static func decodeAudioFileToRedBookPCM(url: URL, maxSeconds: Double = 0.0) throws -> Data {
        let asset = AVURLAsset(url: url)
        let reader = try AVAssetReader(asset: asset)
        guard let track = loadFirstAudioTrackSync(from: asset) else {
            throw NSError(domain: "AudioSampleDecoder", code: -1, userInfo: [NSLocalizedDescriptionKey: "No audio track found in \(url.lastPathComponent)"])
        }

        let outputSettings: [String: Any] = [
            AVFormatIDKey: kAudioFormatLinearPCM,
            AVSampleRateKey: 44_100.0,
            AVNumberOfChannelsKey: 2,
            AVLinearPCMBitDepthKey: 16,
            AVLinearPCMIsFloatKey: false,
            AVLinearPCMIsBigEndianKey: false,
            AVLinearPCMIsNonInterleaved: false
        ]

        let output = AVAssetReaderTrackOutput(track: track, outputSettings: outputSettings)
        output.alwaysCopiesSampleData = false
        reader.add(output)
        guard reader.startReading() else {
            throw NSError(domain: "AudioSampleDecoder", code: -2, userInfo: [NSLocalizedDescriptionKey: "AVAssetReader failed to start on \(url.lastPathComponent)"])
        }

        let maxBytes: Int? = maxSeconds > 0 ? Int(maxSeconds * 44_100.0 * 4.0) : nil
        var pcmData = Data()
        pcmData.reserveCapacity(min(maxBytes ?? 1_764_000, 1_764_000))

        while reader.status == .reading, let sampleBuffer = output.copyNextSampleBuffer() {
            if let blockBuffer = CMSampleBufferGetDataBuffer(sampleBuffer) {
                let length = CMBlockBufferGetDataLength(blockBuffer)
                if length > 0 {
                    var chunk = Data(count: length)
                    chunk.withUnsafeMutableBytes { rawPtr in
                        if let base = rawPtr.baseAddress {
                            _ = CMBlockBufferCopyDataBytes(blockBuffer, atOffset: 0, dataLength: length, destination: base)
                        }
                    }
                    pcmData.append(chunk)
                    if let limit = maxBytes, pcmData.count >= limit {
                        pcmData.removeSubrange(limit..<pcmData.count)
                        reader.cancelReading()
                        break
                    }
                }
            }
        }

        guard !pcmData.isEmpty else {
            throw NSError(domain: "AudioSampleDecoder", code: -3, userInfo: [NSLocalizedDescriptionKey: "Decoded 0 PCM samples from \(url.lastPathComponent)"])
        }

        let remainder = pcmData.count % 2352
        if remainder != 0 {
            pcmData.append(Data(repeating: 0, count: 2352 - remainder))
        }
        return pcmData
    }

    /// Masters an array of audio file URLs into a sector-aligned Red Book `.bin` file and companion `.cue` sheet on disk.
    public static func masterRedBookAudioTracksToDisk(
        sourceURLs: [URL],
        albumTitle: String,
        performer: String,
        outputDirectory: URL,
        crossfadeSeconds: Double = 0.0
    ) throws -> AudioMasteredDiscResult {
        try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
        let safeBase = albumTitle.replacingOccurrences(of: " ", with: "_").uppercased()
        let binURL = outputDirectory.appendingPathComponent("\(safeBase).bin")
        let cueURL = outputDirectory.appendingPathComponent("\(safeBase).cue")

        var combinedPCM = Data()
        var cueLines: [String] = [
            "REM GENERATED BY KROUTON RED BOOK AUDIO ENGINE",
            "PERFORMER \"\(performer)\"",
            "TITLE \"\(albumTitle)\"",
            "FILE \"\(binURL.lastPathComponent)\" BINARY"
        ]

        var boundaryByteOffsets: [Int] = []
        var currentSectorOffset = 0
        for (idx, url) in sourceURLs.enumerated() {
            let trackNum = idx + 1
            let trackPCM = try decodeAudioFileToRedBookPCM(url: url, maxSeconds: 0.0)
            let trackSectors = max(1, trackPCM.count / 2352)

            let mm = (currentSectorOffset / 75) / 60
            let ss = (currentSectorOffset / 75) % 60
            let ff = currentSectorOffset % 75
            let trackTitle = url.deletingPathExtension().lastPathComponent

            cueLines.append(String(format: "  TRACK %02d AUDIO", trackNum))
            cueLines.append("    TITLE \"\(trackTitle)\"")
            cueLines.append("    PERFORMER \"\(performer)\"")
            cueLines.append(String(format: "    INDEX 01 %02d:%02d:%02d", mm, ss, ff))

            if idx > 0 {
                boundaryByteOffsets.append(combinedPCM.count)
            }
            combinedPCM.append(trackPCM)
            currentSectorOffset += trackSectors
        }

        // Apply real 16-bit stereo equal-power crossfade ramps centered across each track boundary
        if crossfadeSeconds > 0, !boundaryByteOffsets.isEmpty {
            let requestedFrames = max(1, Int(crossfadeSeconds * 44_100.0))
            combinedPCM.withUnsafeMutableBytes { rawBuf in
                guard let base = rawBuf.baseAddress?.assumingMemoryBound(to: Int16.self) else { return }
                let totalInt16Count = rawBuf.count / 2
                for boundaryByte in boundaryByteOffsets {
                    let centerSampleIdx = boundaryByte / 2 // stereo interleaved Int16 index
                    let halfSamples = min(requestedFrames * 2, centerSampleIdx, totalInt16Count - centerSampleIdx) & ~1
                    guard halfSamples >= 4 else { continue }
                    let totalFrames = halfSamples / 2
                    for frame in 0..<totalFrames {
                        let t = Double(frame) / Double(max(1, totalFrames - 1))
                        let (gainOut, gainIn) = equalPowerCrossfadeGains(progress: t)
                        let outIdx = (centerSampleIdx - halfSamples) + (frame * 2)
                        let inIdx = centerSampleIdx + (frame * 2)
                        for ch in 0..<2 {
                            let sOut = Double(Int16(littleEndian: base[outIdx + ch]))
                            let sIn = Double(Int16(littleEndian: base[inIdx + ch]))
                            let mixedOut = Int16(clamping: Int((sOut * gainOut + sIn * (1.0 - gainOut)).rounded()))
                            let mixedIn = Int16(clamping: Int((sIn * gainIn + sOut * (1.0 - gainIn)).rounded()))
                            base[outIdx + ch] = mixedOut.littleEndian
                            base[inIdx + ch] = mixedIn.littleEndian
                        }
                    }
                }
            }
        }

        try combinedPCM.write(to: binURL, options: .atomic)
        let cueText = cueLines.joined(separator: "\n") + "\n"
        try Data(cueText.utf8).write(to: cueURL, options: .atomic)

        return AudioMasteredDiscResult(
            binURL: binURL,
            cueURL: cueURL,
            totalSectors2352: combinedPCM.count / 2352,
            totalBytes: Int64(combinedPCM.count),
            cueSheetText: cueText
        )
    }

    /// Synthesizes a valid RIFF WAVE (.wav) file with a 440 Hz stereo sine tone for deterministic AVAssetReader verification.
    public static func synthesizeTestToneWAV(at url: URL, durationSeconds: Double = 0.20) throws {
        let sampleRate: Int = 44_100
        let numFrames = max(588, Int(Double(sampleRate) * durationSeconds))
        let dataByteCount = numFrames * 4
        var wav = Data()
        wav.reserveCapacity(44 + dataByteCount)

        wav.append(contentsOf: Array("RIFF".utf8))
        var chunkSize = UInt32(36 + dataByteCount).littleEndian
        withUnsafeBytes(of: &chunkSize) { wav.append(contentsOf: $0) }
        wav.append(contentsOf: Array("WAVEfmt ".utf8))
        var subchunk1Size = UInt32(16).littleEndian
        withUnsafeBytes(of: &subchunk1Size) { wav.append(contentsOf: $0) }
        var audioFormat = UInt16(1).littleEndian
        var numChannels = UInt16(2).littleEndian
        var srLE = UInt32(sampleRate).littleEndian
        var byteRate = UInt32(sampleRate * 4).littleEndian
        var blockAlign = UInt16(4).littleEndian
        var bitsPerSample = UInt16(16).littleEndian
        withUnsafeBytes(of: &audioFormat) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &numChannels) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &srLE) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &byteRate) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &blockAlign) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &bitsPerSample) { wav.append(contentsOf: $0) }
        wav.append(contentsOf: Array("data".utf8))
        var subchunk2Size = UInt32(dataByteCount).littleEndian
        withUnsafeBytes(of: &subchunk2Size) { wav.append(contentsOf: $0) }

        for i in 0..<numFrames {
            let sample = Int16(sin(2.0 * Double.pi * 440.0 * Double(i) / Double(sampleRate)) * 12_000.0)
            var le = sample.littleEndian
            withUnsafeBytes(of: &le) {
                wav.append(contentsOf: $0)
                wav.append(contentsOf: $0)
            }
        }
        try wav.write(to: url, options: .atomic)
    }
}

// MARK: - Real Hardware Red Book Audio CD TOC Scanner & AudioToolbox Extractor

public struct KroutonMountedCDTrackDescriptor: Identifiable, Sendable, Equatable {
    public var id: Int { trackNumber }
    public let trackNumber: Int
    public let sourceAIFFURL: URL
    public let startBlockLBA: Int
    let frameCount75fps: Int
    public let durationMMSSFF: String
    public let byteSize: Int64
    let preEmphasis: Bool
    public var title: String
    public var performer: String
}

public struct KroutonMountedAudioCDSnapshot: Sendable, Equatable {
    public let mountPath: String
    public let volumeName: String
    public let firstTrack: Int
    let lastTrack: Int
    public let leadoutBlockLBA: Int
    public let musicBrainzDiscID: String
    public var albumTitle: String
    public var albumPerformer: String
    public var tracks: [KroutonMountedCDTrackDescriptor]
    public var totalPCMBytes: Int64 { tracks.reduce(0) { $0 + $1.byteSize } }
}

public struct KroutonRippedTrackResult: Sendable {
    public let trackNumber: Int
    public let outputURL: URL
    public let crc32Hex: String
    public let accurateRipV1Hex: String
    public let bytesWritten: Int64
}

public enum KroutonRealCDExtractor {
    public static func scanMountedAudioCD(preferredMountPath: String? = nil) -> KroutonMountedAudioCDSnapshot? {
        let fm = FileManager.default
        var mounts: [String] = []
        if let pref = preferredMountPath, !pref.isEmpty, fm.fileExists(atPath: (pref as NSString).appendingPathComponent(".TOC.plist")) {
            mounts.append(pref)
        }
        if fm.fileExists(atPath: "/Volumes/Audio CD/.TOC.plist") { mounts.append("/Volumes/Audio CD") }
        if let vols = try? fm.contentsOfDirectory(atPath: "/Volumes") {
            for v in vols.sorted() {
                let p = "/Volumes/\(v)"
                if !mounts.contains(p), fm.fileExists(atPath: "\(p)/.TOC.plist") { mounts.append(p) }
            }
        }
        guard let mountPath = mounts.first,
              let plistData = try? Data(contentsOf: URL(fileURLWithPath: "\(mountPath)/.TOC.plist")),
              let plist = try? PropertyListSerialization.propertyList(from: plistData, options: [], format: nil) as? [String: Any],
              let sessions = plist["Sessions"] as? [[String: Any]],
              let firstSession = sessions.first,
              let trackArray = firstSession["Track Array"] as? [[String: Any]] else { return nil }

        let firstTrack = firstSession["First Track"] as? Int ?? 1
        let lastTrack = firstSession["Last Track"] as? Int ?? trackArray.count
        let leadoutLBA = firstSession["Leadout Block"] as? Int ?? 333_000
        let volName = (mountPath as NSString).lastPathComponent

        let dirFiles = (try? fm.contentsOfDirectory(atPath: mountPath)) ?? []
        var aiffByTrack: [Int: URL] = [:]
        for f in dirFiles where f.lowercased().hasSuffix(".aiff") || f.lowercased().hasSuffix(".aif") {
            if let tNum = Int(f.prefix(while: { $0.isNumber })) {
                aiffByTrack[tNum] = URL(fileURLWithPath: mountPath).appendingPathComponent(f)
            }
        }

        var offsets99 = Array(repeating: 0, count: 100)
        offsets99[0] = leadoutLBA + 150
        var descriptors: [KroutonMountedCDTrackDescriptor] = []

        for (idx, item) in trackArray.enumerated() {
            let tNum = item["Point"] as? Int ?? (idx + 1)
            let startLBA = item["Start Block"] as? Int ?? 150
            let nextLBA = (idx + 1 < trackArray.count) ? (trackArray[idx + 1]["Start Block"] as? Int ?? leadoutLBA) : leadoutLBA
            let frames = max(75, nextLBA - startLBA)
            if tNum >= 1 && tNum <= 99 { offsets99[tNum] = startLBA + 150 }
            if (item["Data"] as? Bool) == true { continue }
            let preEmp = item["Pre-Emphasis Enabled"] as? Bool ?? false
            let aiffURL = aiffByTrack[tNum] ?? URL(fileURLWithPath: mountPath).appendingPathComponent("\(tNum) Audio Track.aiff")
            let fSize = (try? fm.attributesOfItem(atPath: aiffURL.path)[.size] as? Int64) ?? Int64(frames * 2352)
            let baseName = aiffURL.deletingPathExtension().lastPathComponent
            let cleanTitle = baseName.hasSuffix("Audio Track")
                ? String(format: "Track %02d (LBA %d)", tNum, startLBA)
                : baseName
            descriptors.append(KroutonMountedCDTrackDescriptor(
                trackNumber: tNum, sourceAIFFURL: aiffURL, startBlockLBA: startLBA,
                frameCount75fps: frames, durationMMSSFF: KroutonAudioEngine.formatFramesToMMSSFF(Int64(frames)),
                byteSize: fSize, preEmphasis: preEmp, title: cleanTitle,
                performer: volName
            ))
        }

        var hexTOC = String(format: "%02X%02X", firstTrack, lastTrack)
        for off in offsets99 { hexTOC += String(format: "%08X", off) }
        let digest = Insecure.SHA1.hash(data: Data(hexTOC.utf8))
        let mbDiscID = Data(digest).base64EncodedString()
            .replacingOccurrences(of: "+", with: ".").replacingOccurrences(of: "/", with: "_").replacingOccurrences(of: "=", with: "-")

        return KroutonMountedAudioCDSnapshot(
            mountPath: mountPath, volumeName: volName, firstTrack: firstTrack, lastTrack: lastTrack,
            leadoutBlockLBA: leadoutLBA, musicBrainzDiscID: mbDiscID,
            albumTitle: volName == "Audio CD" ? "Audio CD (\(descriptors.count) Tracks)" : volName,
            albumPerformer: "", tracks: descriptors
        )
    }

    private static let opticalRipLock = NSLock()

    public static func extractSingleTrack(
        track: KroutonMountedCDTrackDescriptor,
        codecLabel: String,
        outputDirectory: URL,
        shouldCancel: (@Sendable () -> Bool)? = nil,
        onProgress: (@Sendable (Double, Int64) -> Void)? = nil
    ) throws -> KroutonRippedTrackResult {
        opticalRipLock.lock()
        defer { opticalRipLock.unlock() }

        let fm = FileManager.default
        try fm.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
        let safeTitle = track.title.replacingOccurrences(of: "/", with: "-").replacingOccurrences(of: ":", with: "-").trimmingCharacters(in: .whitespacesAndNewlines)

        let ext: String
        let formatID: AudioFormatID
        let fileTypeID: AudioFileTypeID
        if codecLabel.contains("FLAC") {
            ext = "flac"; formatID = kAudioFormatFLAC; fileTypeID = kAudioFileFLACType
        } else if codecLabel.contains("ALAC") || codecLabel.contains("Apple Lossless") {
            ext = "m4a"; formatID = kAudioFormatAppleLossless; fileTypeID = kAudioFileM4AType
        } else if codecLabel.contains("WAV") {
            ext = "wav"; formatID = kAudioFormatLinearPCM; fileTypeID = kAudioFileWAVEType
        } else {
            ext = "aiff"; formatID = kAudioFormatLinearPCM; fileTypeID = kAudioFileAIFFType
        }

        let outName = String(format: "%02d - %@.%@", track.trackNumber, safeTitle.isEmpty ? "Track" : safeTitle, ext)
        let destURL = outputDirectory.appendingPathComponent(outName)
        if fm.fileExists(atPath: destURL.path) { try? fm.removeItem(at: destURL) }

        var inFile: ExtAudioFileRef?
        var openStatus: OSStatus = -1
        for attempt in 1...4 {
            openStatus = ExtAudioFileOpenURL(track.sourceAIFFURL as CFURL, &inFile)
            if openStatus == noErr, inFile != nil { break }
            Thread.sleep(forTimeInterval: Double(attempt) * 0.25)
        }
        guard openStatus == noErr, let srcRef = inFile else {
            throw NSError(domain: "KroutonRealCDExtractor", code: Int(openStatus), userInfo: [NSLocalizedDescriptionKey: "Cannot open optical track \(track.sourceAIFFURL.lastPathComponent) (OSStatus \(openStatus))"])
        }

        var clientDesc = AudioStreamBasicDescription(
            mSampleRate: 44100.0, mFormatID: kAudioFormatLinearPCM,
            mFormatFlags: kAudioFormatFlagIsSignedInteger | kAudioFormatFlagIsPacked,
            mBytesPerPacket: 4, mFramesPerPacket: 1, mBytesPerFrame: 4, mChannelsPerFrame: 2, mBitsPerChannel: 16, mReserved: 0
        )
        ExtAudioFileSetProperty(srcRef, kExtAudioFileProperty_ClientDataFormat, UInt32(MemoryLayout<AudioStreamBasicDescription>.size), &clientDesc)

        var outDesc = AudioStreamBasicDescription(
            mSampleRate: 44100.0, mFormatID: formatID,
            mFormatFlags: formatID == kAudioFormatLinearPCM ? (fileTypeID == kAudioFileAIFFType ? (kAudioFormatFlagIsBigEndian | kAudioFormatFlagIsSignedInteger | kAudioFormatFlagIsPacked) : (kAudioFormatFlagIsSignedInteger | kAudioFormatFlagIsPacked)) : 0,
            mBytesPerPacket: formatID == kAudioFormatLinearPCM ? 4 : 0, mFramesPerPacket: formatID == kAudioFormatLinearPCM ? 1 : 0,
            mBytesPerFrame: formatID == kAudioFormatLinearPCM ? 4 : 0, mChannelsPerFrame: 2, mBitsPerChannel: 16, mReserved: 0
        )

        var outFile: ExtAudioFileRef?
        let createStatus = ExtAudioFileCreateWithURL(destURL as CFURL, fileTypeID, &outDesc, nil, AudioFileFlags.eraseFile.rawValue, &outFile)
        guard createStatus == noErr, let dstRef = outFile else {
            ExtAudioFileDispose(srcRef)
            throw NSError(domain: "KroutonRealCDExtractor", code: Int(createStatus), userInfo: [NSLocalizedDescriptionKey: "Cannot create output file \(destURL.lastPathComponent) (OSStatus \(createStatus))"])
        }
        ExtAudioFileSetProperty(dstRef, kExtAudioFileProperty_ClientDataFormat, UInt32(MemoryLayout<AudioStreamBasicDescription>.size), &clientDesc)

        let maxAudioFrames = Int64(max(75, track.frameCount75fps - 2)) * 588
        let totalExpectedBytes = max(1, maxAudioFrames * 4)
        let framesPerChunk: UInt32 = 14_700
        let bufBytes = Int(framesPerChunk * 4)
        let rawBuffer = UnsafeMutableRawPointer.allocate(byteCount: bufBytes, alignment: 16)
        defer { rawBuffer.deallocate() }

        var framesReadTotal: Int64 = 0
        var bytesProcessed: Int64 = 0
        var crc: UInt32 = 0xFFFFFFFF
        var arSum: UInt32 = 0
        var sampleIndex: UInt32 = 1

        while framesReadTotal < maxAudioFrames {
            if shouldCancel?() == true {
                ExtAudioFileDispose(dstRef)
                ExtAudioFileDispose(srcRef)
                try? fm.removeItem(at: destURL)
                throw NSError(domain: "KroutonRealCDExtractor", code: -999, userInfo: [NSLocalizedDescriptionKey: "Cancelled"])
            }
            let remainingFrames = UInt32(min(Int64(framesPerChunk), maxAudioFrames - framesReadTotal))
            var numFrames = remainingFrames
            let audioBuf = AudioBuffer(mNumberChannels: 2, mDataByteSize: UInt32(Int(remainingFrames) * 4), mData: rawBuffer)
            var bufList = AudioBufferList(mNumberBuffers: 1, mBuffers: audioBuf)
            let readErr = ExtAudioFileRead(srcRef, &numFrames, &bufList)
            if readErr != noErr || numFrames == 0 { break }

            let validBytes = Int(numFrames * 4)
            let bytePtr = rawBuffer.assumingMemoryBound(to: UInt8.self)
            for i in stride(from: 0, to: validBytes, by: 4) {
                let s32 = UInt32(bytePtr[i]) | (UInt32(bytePtr[i+1]) << 8) | (UInt32(bytePtr[i+2]) << 16) | (UInt32(bytePtr[i+3]) << 24)
                crc = KroutonCRC32.update(crc, bytePtr[i])
                crc = KroutonCRC32.update(crc, bytePtr[i + 1])
                crc = KroutonCRC32.update(crc, bytePtr[i + 2])
                crc = KroutonCRC32.update(crc, bytePtr[i + 3])
                arSum &+= s32 &* sampleIndex
                sampleIndex &+= 1
            }

            let writeErr = ExtAudioFileWrite(dstRef, numFrames, &bufList)
            if writeErr != noErr { break }

            framesReadTotal += Int64(numFrames)
            bytesProcessed += Int64(validBytes)
            onProgress?(min(0.99, Double(bytesProcessed) / Double(totalExpectedBytes)), bytesProcessed)
        }

        ExtAudioFileDispose(dstRef)
        ExtAudioFileDispose(srcRef)
        Thread.sleep(forTimeInterval: 0.15)

        guard bytesProcessed > 0 else {
            try? fm.removeItem(at: destURL)
            throw NSError(domain: "KroutonRealCDExtractor", code: -5, userInfo: [NSLocalizedDescriptionKey: "Zero PCM frames readable on track \(track.trackNumber) (optical media error)"])
        }

        let finalSize = (try? fm.attributesOfItem(atPath: destURL.path)[.size] as? Int64) ?? bytesProcessed
        onProgress?(1.0, finalSize)
        return KroutonRippedTrackResult(
            trackNumber: track.trackNumber,
            outputURL: destURL,
            crc32Hex: String(format: "%08X", ~crc),
            accurateRipV1Hex: String(format: "%08X", arSum),
            bytesWritten: finalSize
        )
    }
}
