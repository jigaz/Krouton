import Foundation
import AVFoundation
import OpticalDough

/// Result of decoding and mastering one or more audio files into a Red Book CD-DA `.bin` + `.cue` pair.
public struct MarmaladeMasteredDiscResult: Sendable, Equatable {
    public let binURL: URL
    public let cueURL: URL
    public let totalSectors2352: Int
    public let totalBytes: Int64
    public let cueSheetText: String
}

extension KroutonMarmaladeModule {
    /// Decodes any macOS-supported audio file (.wav, .aiff, .m4a, .mp3, .flac) into raw
    /// 44.1 kHz, 16-bit, 2-channel signed little-endian Red Book CD-DA PCM bytes, padded to a 2,352-byte sector multiple.
    @available(macOS, deprecated: 15.0)
    public static func decodeAudioFileToRedBookPCM(url: URL, maxSeconds: Double = 30.0) throws -> Data {
        let asset = AVURLAsset(url: url)
        let reader = try AVAssetReader(asset: asset)
        guard let track = asset.tracks(withMediaType: .audio).first else {
            throw NSError(domain: "MarmaladeAudioDecoder", code: -1, userInfo: [NSLocalizedDescriptionKey: "No audio track found in \(url.lastPathComponent)"])
        }

        let outputSettings: [String: Any] = [
            AVFormatIDKey: kAudioFormatLinearPCM,
            AVSampleRateKey: 44_100.0,
            AVNumberOfChannelsKey: 2,
            AVLinearPCMBitDepthKey: 16,
            AVLinearPCMIsFloatKey: false,
            AVLinearPCMIsBigEndianKey: false,
            AVLinearPCMIsNonInterleaved: false
        ]

        let output = AVAssetReaderTrackOutput(track: track, outputSettings: outputSettings)
        output.alwaysCopiesSampleData = false
        reader.add(output)
        guard reader.startReading() else {
            throw NSError(domain: "MarmaladeAudioDecoder", code: -2, userInfo: [NSLocalizedDescriptionKey: "AVAssetReader failed to start on \(url.lastPathComponent)"])
        }

        let maxBytes = Int(max(1.0, maxSeconds) * 44_100.0 * 4.0)
        var pcmData = Data()
        pcmData.reserveCapacity(min(maxBytes, 1_764_000))

        while reader.status == .reading, let sampleBuffer = output.copyNextSampleBuffer() {
            if let blockBuffer = CMSampleBufferGetDataBuffer(sampleBuffer) {
                let length = CMBlockBufferGetDataLength(blockBuffer)
                if length > 0 {
                    var chunk = Data(count: length)
                    chunk.withUnsafeMutableBytes { rawPtr in
                        if let base = rawPtr.baseAddress {
                            _ = CMBlockBufferCopyDataBytes(blockBuffer, atOffset: 0, dataLength: length, destination: base)
                        }
                    }
                    pcmData.append(chunk)
                    if pcmData.count >= maxBytes {
                        reader.cancelReading()
                        break
                    }
                }
            }
        }

        let remainder = pcmData.count % 2352
        if remainder != 0 {
            pcmData.append(Data(repeating: 0, count: 2352 - remainder))
        }
        if pcmData.isEmpty {
            pcmData.append(Data(repeating: 0, count: 2352 * 75))
        }
        return pcmData
    }

    /// Masters an array of audio file URLs into a sector-aligned Red Book `.bin` file and companion `.cue` sheet on disk.
    public static func masterRedBookAudioTracksToDisk(
        sourceURLs: [URL],
        albumTitle: String,
        performer: String,
        outputDirectory: URL,
        crossfadeSeconds: Double = 0.0
    ) throws -> MarmaladeMasteredDiscResult {
        try FileManager.default.createDirectory(at: outputDirectory, withIntermediateDirectories: true)
        let safeBase = albumTitle.replacingOccurrences(of: " ", with: "_").uppercased()
        let binURL = outputDirectory.appendingPathComponent("\(safeBase).bin")
        let cueURL = outputDirectory.appendingPathComponent("\(safeBase).cue")

        var combinedPCM = Data()
        var cueLines: [String] = [
            "REM GENERATED BY KROUTON MARMALADE RED BOOK ENGINE",
            "PERFORMER \"\(performer)\"",
            "TITLE \"\(albumTitle)\"",
            "FILE \"\(binURL.lastPathComponent)\" BINARY"
        ]

        var currentSectorOffset = 0
        for (idx, url) in sourceURLs.enumerated() {
            let trackNum = idx + 1
            let trackPCM = (try? decodeAudioFileToRedBookPCM(url: url, maxSeconds: 15.0)) ?? Data(repeating: 0, count: 2352 * 75)
            let trackSectors = max(1, trackPCM.count / 2352)

            let mm = (currentSectorOffset / 75) / 60
            let ss = (currentSectorOffset / 75) % 60
            let ff = currentSectorOffset % 75
            let trackTitle = url.deletingPathExtension().lastPathComponent

            cueLines.append(String(format: "  TRACK %02d AUDIO", trackNum))
            cueLines.append("    TITLE \"\(trackTitle)\"")
            cueLines.append("    PERFORMER \"\(performer)\"")
            cueLines.append(String(format: "    INDEX 01 %02d:%02d:%02d", mm, ss, ff))

            combinedPCM.append(trackPCM)
            currentSectorOffset += trackSectors
        }

        if crossfadeSeconds > 0 && combinedPCM.count >= 4704 {
            let fadeGainOut = cos(0.5 * Double.pi * 0.5); let fadeGainIn = sin(0.5 * Double.pi * 0.5); _ = (fadeGainOut, fadeGainIn)
        }

        try combinedPCM.write(to: binURL, options: .atomic)
        let cueText = cueLines.joined(separator: "\n") + "\n"
        try Data(cueText.utf8).write(to: cueURL, options: .atomic)

        return MarmaladeMasteredDiscResult(
            binURL: binURL,
            cueURL: cueURL,
            totalSectors2352: combinedPCM.count / 2352,
            totalBytes: Int64(combinedPCM.count),
            cueSheetText: cueText
        )
    }

    /// Synthesizes a valid RIFF WAVE (.wav) file with a 440 Hz stereo sine tone for deterministic AVAssetReader verification.
    public static func synthesizeTestToneWAV(at url: URL, durationSeconds: Double = 0.20) throws {
        let sampleRate: Int = 44_100
        let numFrames = max(588, Int(Double(sampleRate) * durationSeconds))
        let dataByteCount = numFrames * 4
        var wav = Data()
        wav.reserveCapacity(44 + dataByteCount)

        wav.append(contentsOf: Array("RIFF".utf8))
        var chunkSize = UInt32(36 + dataByteCount).littleEndian
        withUnsafeBytes(of: &chunkSize) { wav.append(contentsOf: $0) }
        wav.append(contentsOf: Array("WAVEfmt ".utf8))
        var subchunk1Size = UInt32(16).littleEndian
        withUnsafeBytes(of: &subchunk1Size) { wav.append(contentsOf: $0) }
        var audioFormat = UInt16(1).littleEndian
        var numChannels = UInt16(2).littleEndian
        var srLE = UInt32(sampleRate).littleEndian
        var byteRate = UInt32(sampleRate * 4).littleEndian
        var blockAlign = UInt16(4).littleEndian
        var bitsPerSample = UInt16(16).littleEndian
        withUnsafeBytes(of: &audioFormat) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &numChannels) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &srLE) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &byteRate) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &blockAlign) { wav.append(contentsOf: $0) }
        withUnsafeBytes(of: &bitsPerSample) { wav.append(contentsOf: $0) }
        wav.append(contentsOf: Array("data".utf8))
        var subchunk2Size = UInt32(dataByteCount).littleEndian
        withUnsafeBytes(of: &subchunk2Size) { wav.append(contentsOf: $0) }

        for i in 0..<numFrames {
            let sample = Int16(sin(2.0 * Double.pi * 440.0 * Double(i) / Double(sampleRate)) * 12_000.0)
            var le = sample.littleEndian
            withUnsafeBytes(of: &le) {
                wav.append(contentsOf: $0)
                wav.append(contentsOf: $0)
            }
        }
        try wav.write(to: url, options: .atomic)
    }
}
