#!/usr/bin/env python3
"""Independent reference implementation of the KRSP v1 contract, used only to produce
golden vectors. It shares no code with the Rust or Swift implementations: frames are packed
with `struct`, hashes come from `hashlib`, and X25519 / Ed25519 / HKDF from `cryptography`.

Both `spoold-verify` (Rust) and `krouton-verify` (Swift) load the file this script writes.
If either implementation disagrees with a vector, that implementation has the bug.

    python3 tools/gen_golden_vectors.py > vectors/krsp-golden-v1.txt
"""
import hashlib
import struct

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, x25519
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

out = []


def emit(name, value):
    out.append(f"{name} = {value.hex() if isinstance(value, (bytes, bytearray)) else value}")


def header(kind, flags=0, extent_index=0, first_lba=0, sector_size=0, payload_len=0, digest=bytes(32)):
    return struct.pack(">IBBHIQHHII", 0x4B525350, 1, kind, flags, extent_index, first_lba,
                       sector_size, 0, payload_len, 0) + digest


def leaf(data):
    return hashlib.sha256(b"\x00" + data).digest()


def merkle_root(leaves):
    if not leaves:
        return hashlib.sha256(b"").digest()
    level = list(leaves)
    while len(level) > 1:
        nxt = []
        for i in range(0, len(level), 2):
            nxt.append(level[i] if i + 1 == len(level) else hashlib.sha256(b"\x01" + level[i] + level[i + 1]).digest())
        level = nxt
    return level[0]


def base32_lower(data):
    alphabet = "abcdefghijklmnopqrstuvwxyz234567"
    bits = "".join(f"{b:08b}" for b in data)
    bits += "0" * (-len(bits) % 5)
    return "".join(alphabet[int(bits[i:i + 5], 2)] for i in range(0, len(bits), 5))


def raw(public_key):
    return public_key.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


out.append("# KRSP v1 golden vectors. Generated by tools/gen_golden_vectors.py; do not edit by hand.")

# --- Frames ---------------------------------------------------------------------------------
digest_ab = bytes([0xAB]) * 32
emit("frame.extent_header", header(3, 0, 7, 28, 2352, 2352 * 2, digest_ab))
emit("frame.credit_4", header(6, extent_index=4))
emit("frame.ack_7", header(4, extent_index=7))
emit("frame.flags_and_lba", header(8, flags=0xBEEF, extent_index=0x01020304, first_lba=0x0102030405060708))

# --- Manifest (same deterministic image as Suite 27: 102 sectors x 2352 B, 4 sectors/extent)
image = bytes(((i * 31) + (i >> 9)) & 0xFF for i in range(102 * 2352))
extent = 4 * 2352
leaves = [leaf(image[i:i + extent]) for i in range(0, len(image), extent)]
emit("manifest.sector_size", 2352)
emit("manifest.sectors_per_extent", 4)
emit("manifest.total_sectors", 102)
emit("manifest.extent_count", len(leaves))
emit("manifest.leaf_0", leaves[0])
emit("manifest.leaf_25", leaves[25])
emit("manifest.root", merkle_root(leaves))
three = [hashlib.sha256(bytes([n])).digest() for n in (1, 2, 3)]
emit("merkle.three_leaves_input", b"".join(three))
emit("merkle.three_leaves_root", merkle_root(three))
emit("merkle.empty_root", merkle_root([]))

# --- Bitmap & commit journal ------------------------------------------------------------------
bitmap = bytearray((26 + 7) // 8)
for i in (0, 2, 5, 25):
    bitmap[i // 8] |= 1 << (i % 8)
emit("bitmap.count", 26)
emit("bitmap.set_0_2_5_25", bytes(bitmap))
body = struct.pack(">I", 5) + leaves[5]
emit("journal.record_5", body + hashlib.sha256(body).digest()[:8])

# --- Identity, node ID, TLS pin ---------------------------------------------------------------
alice = ed25519.Ed25519PrivateKey.from_private_bytes(bytes([0x11]) * 32)
bob = ed25519.Ed25519PrivateKey.from_private_bytes(bytes([0x22]) * 32)
bob_pub = raw(bob.public_key())
emit("identity.bob_seed", bytes([0x22]) * 32)
emit("identity.bob_public", bob_pub)
emit("identity.bob_node_id", base32_lower(hashlib.sha256(bob_pub).digest()[:16]))
p256 = ec.derive_private_key(0x4B524F55544F4E, ec.SECP256R1())
x963 = p256.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
emit("tls.p256_x963", x963)
emit("tls.p256_pin", hashlib.sha256(x963).digest())

# --- Pairing (commit-then-reveal numeric comparison) -----------------------------------------
alice_eph = x25519.X25519PrivateKey.from_private_bytes(bytes([0x33]) * 32)
bob_eph = x25519.X25519PrivateKey.from_private_bytes(bytes([0x44]) * 32)
hello_a = raw(alice.public_key()) + raw(alice_eph.public_key()) + bytes([1]) * 16
hello_b = bob_pub + raw(bob_eph.public_key()) + bytes([2]) * 16
emit("pairing.alice_seed", bytes([0x11]) * 32)
emit("pairing.alice_ephemeral_secret", bytes([0x33]) * 32)
emit("pairing.bob_ephemeral_secret", bytes([0x44]) * 32)
emit("pairing.hello_alice", hello_a)
emit("pairing.hello_bob", hello_b)
emit("pairing.commitment_bob", hashlib.sha256(b"krouton-spool-commit-v1" + hello_b).digest())
shared = alice_eph.exchange(x25519.X25519PublicKey.from_public_bytes(hello_b[32:64]))
assert shared == bob_eph.exchange(x25519.X25519PublicKey.from_public_bytes(hello_a[32:64]))
salt = hashlib.sha256(b"krouton-spool-pairing-v1" + hello_a + hello_b).digest()


def hkdf(info, length):
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=salt, info=info).derive(shared)


emit("pairing.salt", salt)
emit("pairing.code", f"{int.from_bytes(hkdf(b'sas', 8), 'big') % 1_000_000:06d}")
emit("pairing.key", hkdf(b"pairing-key", 32))

# --- Session proof (Ed25519 is deterministic, so the signature is a fixed vector) -----------
exporter = bytes([7]) * 32
message = b"krouton-spool-session-v1|node|" + exporter
emit("session.exporter", exporter)
emit("session.message", message)
emit("session.signature_bob_node", bob.sign(message))

print("\n".join(out))
