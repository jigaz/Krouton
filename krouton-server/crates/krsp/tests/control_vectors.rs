#[test]
fn control_vectors_round_trip_exactly() {
    let expected: String =
        canonical().iter().map(|(name, c)| format!("{name} = {}\n", c.to_value().to_json())).collect::<String>();
    let header =
        "# KRSP v1 control messages (kind-8 JSON). Generated by krsp/tests/control_vectors.rs; do not edit by hand.\n";
    if std::env::var_os("KRSP_WRITE_CONTROL_VECTORS").is_some() {
        std::fs::write(PATH, format!("{header}{expected}")).unwrap();
    }
    let file = std::fs::read_to_string(PATH).expect("Vectors/krsp-control-v1.txt is missing").replace("\r\n", "\n");
    let mut seen = 0;
    for line in file.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
        let (name, text) = line.split_once(" = ").unwrap();
        let value = json::parse(text.as_bytes()).unwrap_or_else(|e| panic!("{name}: {e}"));
        let control = Control::from_value(&value).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert_eq!(control.to_value().to_json(), text, "{name} must re-encode byte for byte");
        seen += 1;
    }
    assert_eq!(seen, canonical().len());
    assert_eq!(file.trim_start_matches(header), expected);
}
