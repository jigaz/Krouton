//! `Vectors/krsp-bundle-v1.tar` and `Vectors/krsp-bundle-names-v1.txt`, shared with the Swift
//! app (`krouton-verify` Suite 27): the Swift writer must produce the same archive byte for byte,
//! and both sides must accept and reject the same names. Regenerate with
//! `KRSP_WRITE_BUNDLE_VECTORS=1 cargo test -p krsp --test bundle_vectors`.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use krsp::bundle::{BundleReader, BundleWriter, EntryKind, validate_path};
use krsp::json::Value;

const ARCHIVE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../../Vectors/krsp-bundle-v1.tar");
const NAMES: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../../Vectors/krsp-bundle-names-v1.txt");

/// (path, None = folder / Some(contents), mtime)
fn canonical() -> Vec<(String, Option<Vec<u8>>, u64)> {
    let long = format!("Holiday 2026/{}.txt", "a-very-long-file-name-that-needs-a-pax-header".repeat(2));
    vec![
        ("Holiday 2026".into(), None, 1_767_225_600),
        ("Holiday 2026/README.txt".into(), Some(b"Burned by Krouton.\n".to_vec()), 1_767_225_601),
        ("Holiday 2026/Fotos \u{2013} \u{dc}n\u{ef}code".into(), None, 1_767_225_602),
        (
            "Holiday 2026/Fotos \u{2013} \u{dc}n\u{ef}code/IMG_0001.JPG".into(),
            Some((0..3).flat_map(|_| 0..=255u8).collect()),
            1_767_225_603,
        ),
        (long, Some(b"long\n".to_vec()), 1_767_225_604),
        ("empty.bin".into(), Some(Vec::new()), 0),
    ]
}

fn names() -> Vec<(bool, String)> {
    let accept = [
        "a",
        "Photos/2026/IMG 0001.JPG",
        "CONSOLE.txt",
        "com10",
        "LPT0",
        ".hidden",
        "Fotos \u{2013} \u{dc}n\u{ef}code/caf\u{e9}.txt",
        "emoji \u{1f4bf}.txt",
    ];
    let reject = [
        "",
        "/abs",
        "a//b",
        "a/./b",
        "../up",
        "a:b",
        "a\\b",
        "what?",
        "star*",
        "quote\"",
        "lt<",
        "gt>",
        "pipe|",
        "bell\u{7}",
        "del\u{7f}",
        "trailing.",
        "space ",
        "con",
        "Aux.txt",
        "NUL.tar.gz",
        "COM1",
        "lpt9.log",
    ];
    let long_name = "n".repeat(256);
    let deep = "d/".repeat(65);
    let mut out: Vec<(bool, String)> = accept.iter().map(|s| (true, (*s).to_owned())).collect();
    out.push((true, "n".repeat(255)));
    out.push((true, "d/".repeat(64).trim_end_matches('/').to_owned()));
    out.extend(reject.iter().map(|s| (false, (*s).to_owned())));
    out.push((false, long_name));
    out.push((false, deep.trim_end_matches('/').to_owned()));
    out.push((false, format!("{}/x", "p".repeat(200)).repeat(6)));
    out
}

fn build() -> Vec<u8> {
    let mut w = BundleWriter::new(Vec::new());
    for (path, data, mtime) in canonical() {
        match data {
            None => w.directory(&path, mtime).unwrap(),
            Some(d) => w.file(&path, d.len() as u64, mtime, &mut d.as_slice()).unwrap(),
        }
    }
    w.finish().unwrap()
}

#[test]
fn bundle_vector_is_canonical_and_reads_back() {
    let bytes = build();
    if std::env::var_os("KRSP_WRITE_BUNDLE_VECTORS").is_some() {
        std::fs::write(ARCHIVE, &bytes).unwrap();
    }
    let stored = std::fs::read(ARCHIVE).expect("Vectors/krsp-bundle-v1.tar is missing");
    assert_eq!(stored, bytes, "the writer's output changed; regenerate only for a deliberate format change");

    let mut reader = BundleReader::new(stored.as_slice());
    for (path, data, mtime) in canonical() {
        let entry = reader.next_entry().unwrap().unwrap();
        assert_eq!(entry.path, path);
        assert_eq!(entry.mtime, mtime);
        let mut got = Vec::new();
        reader.copy_data(&mut got, &|| true).unwrap();
        match data {
            None => assert_eq!(entry.kind, EntryKind::Directory),
            Some(d) => assert_eq!(got, d),
        }
    }
    assert!(reader.next_entry().unwrap().is_none());
}

#[test]
fn name_vectors_match_the_rules() {
    let text: String = names()
        .into_iter()
        .map(|(ok, name)| format!("{} {}\n", if ok { "accept" } else { "reject" }, Value::from(name).to_json()))
        .collect();
    let header =
        "# KRSP bundle v1 path rules: accept/reject + JSON string. Generated by krsp/tests/bundle_vectors.rs.\n";
    if std::env::var_os("KRSP_WRITE_BUNDLE_VECTORS").is_some() {
        std::fs::write(NAMES, format!("{header}{text}")).unwrap();
    }
    let stored =
        std::fs::read_to_string(NAMES).expect("Vectors/krsp-bundle-names-v1.txt is missing").replace("\r\n", "\n");
    assert_eq!(stored.trim_start_matches(header), text);
    for (ok, name) in names() {
        assert_eq!(validate_path(&name).is_ok(), ok, "{name:?}");
    }
}
