# Wrap static Text("...") literals (without string interpolation `\(`) in store.tr("...")
def localize_swift_literals(code):
    # 1. Text("literal") -> Text(store.tr("literal"))
    def repl_text(m):
        inner = m.group(1)
        if "\\(" in inner or inner.strip() == "":
            return m.group(0)
        return f'Text(store.tr("{inner}"))'
    code = re.sub(r'\bText\("([^"\\]+)"\)', repl_text, code)

    # 2. Toggle("literal", isOn: ...) -> Toggle(store.tr("literal"), isOn: ...)
    def repl_toggle(m):
        inner = m.group(1)
        if "\\(" in inner or inner.strip() == "":
            return m.group(0)
        return f'Toggle(store.tr("{inner}"), isOn:'
    code = re.sub(r'\bToggle\("([^"\\]+)",\s*isOn:', repl_toggle, code)

    # 3. Label("literal", systemImage: ...) -> Label(store.tr("literal"), systemImage: ...)
    def repl_label(m):
        inner = m.group(1)
        if "\\(" in inner or inner.strip() == "":
            return m.group(0)
        return f'Label(store.tr("{inner}"), systemImage:'
    code = re.sub(r'\bLabel\("([^"\\]+)",\s*systemImage:', repl_label, code)

    # 4. TableColumn("literal", value: ...) -> TableColumn(store.tr("literal"), value: ...)
    def repl_col(m):
        inner = m.group(1)
        if "\\(" in inner or inner.strip() == "":
            return m.group(0)
        return f'TableColumn(store.tr("{inner}"), value:'
    code = re.sub(r'\bTableColumn\("([^"\\]+)",\s*value:', repl_col, code)

    return code

s_text = localize_swift_literals(s_text)

